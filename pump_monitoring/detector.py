from pathlib import Path
import joblib
import numpy as np
from .simulator import FEATURES, generate_labeled_dataset


class PumpFaultDetector:
    """Random Forest demonstration classifier trained only on synthetic scenarios."""
    def __init__(self, model_path: str | Path = "./models/pump_fault_classifier.joblib"):
        self.model_path = Path(model_path)
        self.model = None
        if self.model_path.exists():
            self.model = joblib.load(self.model_path)

    def train(self, n_per_scenario: int = 500, seed: int = 42):
        from sklearn.ensemble import RandomForestClassifier
        from sklearn.model_selection import train_test_split
        from sklearn.metrics import accuracy_score, classification_report

        rows = generate_labeled_dataset(n_per_scenario, seed)
        X = np.asarray([[r[f] for f in FEATURES] for r in rows], dtype=float)
        y = np.asarray([r["scenario"] for r in rows])
        X_train, X_test, y_train, y_test = train_test_split(
            X, y, test_size=0.25, random_state=seed, stratify=y
        )
        model = RandomForestClassifier(
            n_estimators=220, max_depth=12, min_samples_leaf=2,
            class_weight="balanced", random_state=seed, n_jobs=-1
        )
        model.fit(X_train, y_train)
        pred = model.predict(X_test)
        metrics = {
            "accuracy_on_synthetic_holdout": float(accuracy_score(y_test, pred)),
            "classification_report": classification_report(y_test, pred, output_dict=True, zero_division=0),
            "training_rows": int(len(X_train)),
            "test_rows": int(len(X_test)),
            "classes": list(model.classes_),
            "dataset": "synthetic scenarios generated by pump_monitoring.simulator",
        }
        self.model_path.parent.mkdir(parents=True, exist_ok=True)
        joblib.dump(model, self.model_path)
        self.model = model
        return metrics

    def predict(self, reading: dict) -> tuple[str, float, str]:
        if self.model is None:
            self.train()
        vector = np.asarray([[float(reading[f]) for f in FEATURES]], dtype=float)
        probabilities = self.model.predict_proba(vector)[0]
        best_idx = int(np.argmax(probabilities))
        condition = str(self.model.classes_[best_idx])
        confidence = float(probabilities[best_idx])
        anomaly_score = round(1.0 - confidence, 4)
        severity = "normal" if condition == "normal" else ("high" if condition in {"overload", "cavitation"} else "warning")
        explanation = {
            "normal": "Sensor pattern is closest to the synthetic normal-operation class.",
            "bearing_wear": "Pattern resembles the synthetic bearing-wear scenario; inspect vibration and bearing temperature.",
            "misalignment": "Pattern resembles the synthetic misalignment scenario; inspect vibration and alignment.",
            "cavitation": "Pattern resembles the synthetic cavitation scenario; review suction conditions and flow measurements.",
            "overload": "Pattern resembles the synthetic overload scenario; review motor current and temperature.",
            "low_flow": "Pattern resembles the synthetic low-flow scenario; review flow path and operating conditions.",
        }[condition]
        return condition, anomaly_score, f"{explanation} Model confidence: {confidence:.1%}."
